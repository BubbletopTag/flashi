// Generates src/theme/tokens.flashi.css: a Material 3 tonal palette from the
// seed #8BC34A (light green) using @material/material-color-utilities
// (Apache-2.0). Answer-button and count colours keep AnkiDroid's functional
// semantics (again red, hard grey, good green, easy blue).
// Usage: npx tsx scripts/make-flashi-theme.mjs
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, TonalPalette } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";

const SEED = "#8BC34A";
const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), false, 0);
const primary = TonalPalette.fromInt(argbFromHex(SEED));
const neutral = scheme.neutralPalette;
const hex = (argb) => hexFromArgb(argb).toUpperCase();
const tone = (palette, t) => hex(palette.tone(t));

function luminance(h) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
const contrast = (a, b) => {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

const t = {
  "--primary": hex(scheme.primary),
  "--on-primary": hex(scheme.onPrimary),
  "--primary-dark": tone(scheme.primaryPalette, 30),
  "--accent": hex(scheme.secondary),
  "--window-bg": hex(scheme.surface),
  "--on-surface": hex(scheme.onSurface),
  "--on-surface-variant": hex(scheme.onSurfaceVariant),
  "--surface-variant": hex(scheme.surfaceVariant),
  "--surface-container": hex(scheme.surfaceContainer),
  "--surface-container-high": hex(scheme.surfaceContainerHigh),
  "--outline-variant": hex(scheme.outlineVariant),
  "--current-deck-bg": hex(scheme.surfaceContainerHighest),
  "--topbar": tone(scheme.primaryPalette, 94),
  "--fab": hex(scheme.primaryContainer),
  "--on-fab": hex(scheme.onPrimaryContainer),
  "--divider": tone(neutral, 90),
};
const checks = [
  ["toolbar text", t["--on-primary"], t["--primary"]],
  ["body text", t["--on-surface"], t["--window-bg"]],
  ["fab icon", t["--on-fab"], t["--fab"]],
  ["counts on topbar (new)", "#303F9F", t["--topbar"]],
  ["counts on topbar (learn)", "#C62828", t["--topbar"]],
  ["counts on topbar (review)", "#1B5E20", t["--topbar"]],
];
for (const [name, fg, bg] of checks) {
  const c = contrast(fg, bg);
  console.log(`${name}: ${c.toFixed(2)}:1 ${c >= 4.5 ? "ok" : "LOW"}`);
}
const css = `/* SPDX-License-Identifier: AGPL-3.0-or-later */
/* Generated by scripts/make-flashi-theme.mjs from seed ${SEED} (Material 3 tonal spot).
   Do not edit by hand; tweak the script and re-run it. */
:root,
:root[data-theme="flashi"] {
${Object.entries(t).map(([k, v]) => `  ${k}: ${v};`).join("\n")}
  --count-new: #303F9F;
  --count-learn: #C62828;
  --count-review: #1B5E20;
  --count-zero: rgba(0, 0, 0, 0.12);
  --btn-again: #D32F2F; --btn-hard: #455A64; --btn-good: #388E3C; --btn-easy: #0277BD;
  --btn-again-pressed: #F44336; --btn-hard-pressed: #B0BEC5; --btn-good-pressed: #66BB6A; --btn-easy-pressed: #29B6F6;
  --btn-text: #FFFFFF;
  --show-answer: var(--btn-hard);
  --show-answer-pressed: var(--btn-hard-pressed);
  --text: var(--on-surface);
  --text-secondary: var(--on-surface-variant);
  --dyn-deck: #2222BB;
  --snackbar: #424242;
  --snackbar-action: ${tone(primary, 80)};
  --scrim: rgba(0, 0, 0, 0.32);
  --flag-red: #FF4747; --flag-orange: #FFB647; --flag-green: #6FF06F; --flag-blue: #5289FF;
  --flag-pink: #FF99F1; --flag-turquoise: #85FFEF; --flag-purple: #C398EC;
  color-scheme: light;
}
`;
writeFileSync(new URL("../src/theme/tokens.flashi.css", import.meta.url), css);
console.log(css);
