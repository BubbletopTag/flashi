"""Generate test decks and the default schema-11 collection template.

Requires the official `anki` package (AGPL) and `genanki` (MIT):
    pip install anki genanki

Outputs:
  src/anki/defaults.json               default `col` row JSON of a new collection
                                       (stock note types, Default deck/preset, conf)
  fixtures/decks/legacy-anki21.apkg    "Support older Anki versions" export (schema 11)
  fixtures/decks/latest-anki21b.apkg   current default export (zstd, schema 18)
  fixtures/decks/genanki-anki2.apkg    genanki output (collection.anki2 only, no meta)
  fixtures/decks/schema18-noscheduling.apkg  current export without scheduling
"""

from __future__ import annotations

import json
import os
import shutil
import sqlite3
import struct
import sys
import tempfile
import time
import zlib

from anki.collection import Collection, ExportAnkiPackageOptions

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DECKS = os.path.join(ROOT, "fixtures", "decks")


def png(width: int, height: int, rgb: tuple[int, int, int]) -> bytes:
    raw = b"".join(b"\x00" + bytes(rgb) * width for _ in range(height))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")


def wav(freq: float = 440.0, ms: int = 200, rate: int = 8000) -> bytes:
    import math

    n = rate * ms // 1000
    samples = bytes(int(128 + 100 * math.sin(2 * math.pi * freq * i / rate)) for i in range(n))
    header = b"RIFF" + struct.pack("<I", 36 + n) + b"WAVEfmt " + struct.pack("<IHHIIHH", 16, 1, 1, rate, rate, 1, 8)
    return header + b"data" + struct.pack("<I", n) + samples


def dump_defaults() -> None:
    d = tempfile.mkdtemp()
    path = os.path.join(d, "collection.anki2")
    col = Collection(path)
    col.close(downgrade=True)
    db = sqlite3.connect(path)
    conf, models, decks, dconf, tags = db.execute("select conf, models, decks, dconf, tags from col").fetchone()
    out = {
        "_comment": "Generated by scripts/make-fixtures.py from a new collection made by the official anki package, downgraded to schema 11.",
        "conf": json.loads(conf),
        "models": list(json.loads(models).values()),
        "decks": list(json.loads(decks).values()),
        "dconf": list(json.loads(dconf).values()),
        "tags": json.loads(tags),
    }
    with open(os.path.join(ROOT, "src", "anki", "defaults.json"), "w") as f:
        json.dump(out, f, indent=1, ensure_ascii=False)
        f.write("\n")


def build_collection() -> tuple[Collection, str]:
    d = tempfile.mkdtemp()
    col = Collection(os.path.join(d, "collection.anki2"))
    media = col.media.dir()
    files = {
        "green.png": png(32, 20, (139, 195, 74)),
        "日本.png": png(16, 16, (200, 40, 40)),
        "beep.wav": wav(),
    }
    for name, data in files.items():
        with open(os.path.join(media, name), "wb") as fh:
            fh.write(data)

    mm = col.models
    basic = mm.by_name("Basic")
    reverse = mm.by_name("Basic (and reversed card)")
    cloze = mm.by_name("Cloze")
    typein = mm.by_name("Basic (type in the answer)")

    # A Japanese note type using furigana filters and {{Tags}}/{{Deck}} specials.
    jp = mm.new("Japanese (Flashi test)")
    for fname in ("Expression", "Reading", "Meaning"):
        mm.add_field(jp, mm.new_field(fname))
    t = mm.new_template("Recognition")
    t["qfmt"] = '<div class="big">{{kanji:Reading}}</div>'
    t["afmt"] = '{{FrontSide}}<hr id=answer>{{furigana:Reading}}<br>{{Meaning}}<br><small>{{Tags}} · {{Deck}} · {{Subdeck}} · {{Card}}</small>'
    mm.add_template(jp, t)
    jp["css"] += "\n.big { font-size: 40px; }\n"
    mm.add(jp)
    jp = mm.by_name("Japanese (Flashi test)")

    def add(model, deck: str, fields: list[str], tags: str = "") -> list[int]:
        note = col.new_note(model)
        for i, v in enumerate(fields):
            note.fields[i] = v
        note.tags = tags.split()
        col.add_note(note, col.decks.id(deck))
        return [c.id for c in note.cards()]

    add(basic, "Flashi Test::Basics", ["What colour is this? <img src=\"green.png\">", "Light green"], "colour image")
    add(basic, "Flashi Test::Basics", ["Play the sound [sound:beep.wav]", "A 440 Hz beep"], "audio")
    add(basic, "Flashi Test::Basics", ["<b>Bold</b>, <i>italic</i> &amp; <u>underline</u>", "HTML &lt;works&gt;"])
    add(basic, "Flashi Test::Basics", ['Unicode media: <img src="日本.png">', "Red square"])
    add(reverse, "Flashi Test::Basics", ["Hund", "dog"], "german vocab")
    add(reverse, "Flashi Test::Basics", ["Katze", "cat"], "german vocab")
    add(cloze, "Flashi Test::Cloze", ["{{c1::Canberra}} is the capital of {{c2::Australia::country}}.", "Extra info"], "geography")
    add(cloze, "Flashi Test::Cloze", ["The {{c1::mitochondria}} is the {{c1::powerhouse}} of the cell.", ""], "biology")
    add(typein, "Flashi Test::Type", ["Spell 'necessary'", "necessary"])
    add(basic, "Flashi Test::Math", [r"Solve \(x^2 = 4\)", r"\[x = \pm 2\]"], "math")
    add(jp, "Flashi Test::Japanese", ["日本語", "日本語[にほんご]", "Japanese language"], "japanese")
    add(jp, "Flashi Test::Japanese", ["食べる", "食[た]べる", "to eat"], "japanese verb")
    for i in range(25):
        add(basic, "Flashi Test::Many", [f"Question {i + 1}", f"Answer {i + 1}"])

    # Give some cards scheduling history, through Anki's own scheduler.
    col.decks.select(col.decks.id("Flashi Test::Many"))
    for rating in (3, 3, 4, 1, 3, 2, 3, 4):
        queued = col.sched.get_queued_cards()
        if not queued.cards:
            break
        qc = queued.cards[0]
        card = col.get_card(qc.card.id)
        card.start_timer()
        col.sched.answer_card(col.sched.build_answer(card=card, states=qc.states, rating=rating - 1))
    # And a few mature reviews, set directly.
    today = col.sched.today
    many = col.decks.id("Flashi Test::Many")
    ids = col.db.list("select id from cards where did=? and queue=0 order by due limit 5", many)
    for i, cid in enumerate(ids):
        col.db.execute(
            "update cards set type=2, queue=2, ivl=?, due=?, factor=2500, reps=4 where id=?",
            10 + i * 7,
            today + i - 2,
            cid,
        )
    return col, d


def export(col: Collection, name: str, legacy: bool, with_scheduling: bool = True) -> None:
    opts = ExportAnkiPackageOptions(
        with_scheduling=with_scheduling, with_deck_configs=True, with_media=True, legacy=legacy
    )
    col.export_anki_package(out_path=os.path.join(DECKS, name), options=opts, limit=None)


def genanki_deck() -> None:
    import genanki

    model = genanki.Model(
        1607392319,
        "Simple Model (genanki)",
        fields=[{"name": "Question"}, {"name": "Answer"}],
        templates=[
            {
                "name": "Card 1",
                "qfmt": "{{Question}}",
                "afmt": '{{FrontSide}}<hr id="answer">{{Answer}}',
            }
        ],
    )
    deck = genanki.Deck(2059400110, "Genanki Legacy")
    for i in range(5):
        deck.add_note(genanki.Note(model=model, fields=[f"genanki Q{i}", f"genanki A{i} <img src=\"g.png\">"]))
    tmp = tempfile.mkdtemp()
    img = os.path.join(tmp, "g.png")
    with open(img, "wb") as fh:
        fh.write(png(8, 8, (3, 169, 244)))
    pkg = genanki.Package(deck)
    pkg.media_files = [img]
    pkg.write_to_file(os.path.join(DECKS, "genanki-anki2.apkg"))


def main() -> None:
    os.makedirs(DECKS, exist_ok=True)
    dump_defaults()
    col, _ = build_collection()
    export(col, "legacy-anki21.apkg", legacy=True)
    export(col, "latest-anki21b.apkg", legacy=False)
    export(col, "schema18-noscheduling.apkg", legacy=False, with_scheduling=False)
    col.close()
    genanki_deck()
    print("wrote", sorted(os.listdir(DECKS)))


if __name__ == "__main__":
    sys.exit(main())
